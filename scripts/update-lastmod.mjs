// Refreshes src/data/lastmod.js: the <lastmod> date for each URL in
// sitemap.xml, taken from the last git commit that touched the files that
// make the page. Run `npm run lastmod` before a release.
//
// Not part of `npm run build` on purpose. Cloudflare builds from a shallow
// clone, where every file would appear to have been changed on the deploy day,
// which is exactly the "same date for every URL" signal a sitemap should not
// send. The committed file is the source of truth; this only refreshes it.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const load = (rel) => import(pathToFileURL(path.join(root, rel)).href)

const { TEMPLATES } = await load('src/data/templatesData.js')
const { SATSANG_TEMPLATES } = await load('src/data/satsangTemplatesData.js')
const { GANESH_TEMPLATES } = await load('src/data/ganeshTemplatesData.js')
const { BLOG_POSTS } = await load('src/data/blogPosts.js')

function lastCommit(files) {
  const dates = files
    .map((file) => {
      try {
        return execFileSync('git', ['log', '-1', '--format=%cs', '--', file], { cwd: root, encoding: 'utf8' }).trim()
      } catch {
        return ''
      }
    })
    .filter(Boolean)
    .sort()
  return dates.at(-1) ?? null
}

// What a template page is made of: its own component folder if it has one,
// otherwise the shared layout, plus the page copy and the page component.
const COPY = ['src/data/templateCopy.js', 'src/data/templateSeo.js', 'src/components/TemplatePageContent.jsx']
const SHARED_WEDDING = ['src/components/InvitationExperience.jsx', 'src/components/WelcomeSplash.jsx']
const WEDDING_DIRS = {
  'mahogany-seal': 'src/components/templates/MahoganySealTemplate',
  'velvet-theatre': 'src/components/templates/VelvetTheatreTemplate',
  'rang-mahal': 'src/components/templates/RangMahalTemplate',
}
const SATSANG_DIRS = {
  'shukrana-darshan': 'src/components/templates/ShukranaDarshanTemplate',
  'gulab-marg': 'src/components/templates/GulabMargTemplate',
}

const lastmod = {}
const pages = {
  '/': ['src/components/LandingPage.jsx'],
  '/about': ['src/pages/AboutPage.jsx'],
  '/weddings': ['src/pages/WeddingsPage.jsx'],
  '/guruji-satsangs': ['src/pages/GurujiSatsangsPage.jsx'],
  '/templates/ganesh-chaturthi': ['src/pages/GaneshChaturthiPage.jsx'],
  '/create': ['src/pages/CreateInvitePage.jsx'],
  '/partners': ['src/pages/partners/PartnerLandingPage.jsx'],
  '/privacy': ['src/pages/PrivacyPolicyPage.jsx'],
  '/terms': ['src/pages/TermsOfServicePage.jsx'],
  '/refund': ['src/pages/RefundPolicyPage.jsx'],
}
for (const [urlPath, files] of Object.entries(pages)) lastmod[urlPath] = lastCommit(files)

for (const t of TEMPLATES.filter((x) => !x.hidden)) {
  lastmod[`/templates/wedding/${t.id}`] = lastCommit([...(WEDDING_DIRS[t.id] ? [WEDDING_DIRS[t.id]] : SHARED_WEDDING), ...COPY])
}
for (const t of SATSANG_TEMPLATES.filter((x) => x.fullExperience)) {
  lastmod[`/satsang/${t.slug}`] = lastCommit([SATSANG_DIRS[t.slug] ?? 'src/components/SatsangExperience.jsx', ...COPY])
}
for (const t of GANESH_TEMPLATES) {
  lastmod[`/templates/ganesh-chaturthi/${t.slug}`] = lastCommit([`src/components/ganesh/${t.layout ?? ''}`, 'src/data/ganeshTemplatesData.js', ...COPY])
}

// Blog posts carry their own dates in the data.
for (const post of BLOG_POSTS) lastmod[`/blog/${post.slug}`] = post.updated || post.date
lastmod['/blog'] = [lastCommit(['src/pages/BlogListPage.jsx']), ...BLOG_POSTS.map((p) => p.updated || p.date)].filter(Boolean).sort().at(-1)

const lines = Object.entries(lastmod)
  .filter(([, date]) => date)
  .map(([urlPath, date]) => `  '${urlPath}': '${date}',`)

writeFileSync(
  path.join(root, 'src/data/lastmod.js'),
  `// Generated by scripts/update-lastmod.mjs (npm run lastmod). Do not edit by hand.
// The <lastmod> date of each sitemap URL: the last commit that touched the
// files the page is made of, or the post's own date for a blog post.
export const LASTMOD = {
${lines.join('\n')}
}
`,
)
console.log(`wrote ${lines.length} dates to src/data/lastmod.js`)
