import { useCallback, useEffect, useMemo, useState } from 'react'
import { CheckCircle2, Copy, ExternalLink, Gauge, Link2, Loader2, Search } from 'lucide-react'
import SEO from '../../components/SEO'
import AdminForbidden from '../../components/admin/AdminForbidden'
import Pagination from '../../components/partners/Pagination'
import { usePartnerAuth } from '../../hooks/usePartnerAuth'
import { adminListInvites } from '../../utils/partnerApi'
import { formatInviteDate } from '../../utils/formatInviteDateTime'

const PAGE_SIZE = 10

const SOURCE_TABS = [
  { value: 'all', label: 'All' },
  { value: 'direct', label: 'Direct' },
  { value: 'partner', label: 'Partner' },
]

function SourceBadge({ source, businessName }) {
  return (
    <span
      className={`inline-flex items-center rounded-full px-2.5 py-1 text-xs font-medium ${
        source === 'partner' ? 'bg-champagne text-ink-soft' : 'bg-blush text-rose'
      }`}
      title={source === 'partner' ? businessName : 'Self-serve, no partner'}
    >
      {source === 'partner' ? businessName || 'Partner' : 'Direct'}
    </span>
  )
}

function CopyLinkButton({ url }) {
  const [copied, setCopied] = useState(false)
  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(url)
      setCopied(true)
      setTimeout(() => setCopied(false), 2000)
    } catch (err) {
      console.error('[AdminInvites] clipboard copy failed:', err)
    }
  }
  return (
    <button
      type="button"
      onClick={handleCopy}
      className="inline-flex shrink-0 items-center gap-1 rounded-full border border-champagne-deep/50 bg-ivory/70 px-2.5 py-1.5 text-xs text-ink hover:bg-ivory"
    >
      {copied ? <CheckCircle2 className="h-3 w-3" /> : <Copy className="h-3 w-3" />}
      {copied ? 'Copied' : 'Copy'}
    </button>
  )
}

// A flex ROW where the link itself carries min-w-0 + flex-1 + truncate
// directly (no nested span-in-flex-in-flex) — that's what makes the
// ellipsis truncation actually take effect instead of the full URL
// overflowing its row and bleeding into the row/button beside it. Flex
// items default to min-width: auto (their own content width as a floor),
// which silently defeats `truncate` on any descendant unless the item
// that carries `truncate` also opts out of that floor with `min-w-0`.
//
// The label column is `truncate` too, not just a fixed width: "Dashboard"
// (9 letters, uppercase, letter-spaced) is wider than "Member" (6) and, at
// a `w-*` width sized for the shorter word, was overflowing its box with
// no clipping — text-overflow only clips when `overflow-hidden` is
// actually set, plain `w-16` alone constrains the layout box but not the
// visible text — so it silently rendered on top of the link text right
// next to it.
function LinkRow({ label, url }) {
  return (
    <div className="flex min-w-0 items-center gap-2 text-xs">
      <span className="w-24 shrink-0 truncate uppercase tracking-[0.1em] text-ink-soft">{label}</span>
      {url ? (
        <>
          <a
            href={url}
            target="_blank"
            rel="noreferrer"
            className="min-w-0 flex-1 truncate text-ink-soft hover:text-rose"
          >
            {url}
          </a>
          <ExternalLink className="h-3 w-3 shrink-0 text-ink-soft/50" />
          <CopyLinkButton url={url} />
        </>
      ) : (
        <span className="text-ink-soft/60">— not available</span>
      )}
    </div>
  )
}

// "Member Links" in the admin sidebar (see AdminShell.jsx) — a super admin's
// single view over every invite in the system, whether it was generated by
// a partner spending a credit (/partners/dashboard/create) or a couple
// self-serving through the Invitation Builder (/create). Each row surfaces
// both the public member link and, for direct invites, the private host
// dashboard link — the same two links the partner/host themselves would
// use — so an admin never needs direct database access to open either one
// on someone's behalf. See api/_lib/adminInvites.js.
export default function AdminInvitesPage() {
  const { accessToken } = usePartnerAuth()
  const [invites, setInvites] = useState(null)
  const [status, setStatus] = useState('loading') // loading | success | forbidden | error
  const [source, setSource] = useState('all')
  const [query, setQuery] = useState('')
  const [page, setPage] = useState(1)

  const load = useCallback(async () => {
    setStatus('loading')
    try {
      const result = await adminListInvites(accessToken)
      setInvites(result.invites)
      setStatus('success')
    } catch (err) {
      setStatus(/not authorized|sign in required/i.test(err.message || '') ? 'forbidden' : 'error')
    }
  }, [accessToken])

  useEffect(() => {
    load()
  }, [load])

  const filtered = useMemo(() => {
    const list = invites || []
    const bySource = source === 'all' ? list : list.filter((inv) => inv.source === source)
    const q = query.trim().toLowerCase()
    if (!q) return bySource
    return bySource.filter((inv) =>
      [inv.names, inv.venue, inv.businessName, inv.hostEmail, inv.slug].some((field) =>
        String(field ?? '').toLowerCase().includes(q),
      ),
    )
  }, [invites, source, query])

  useEffect(() => {
    setPage(1)
  }, [source, query])

  const pageCount = Math.max(1, Math.ceil(filtered.length / PAGE_SIZE))
  const pageInvites = filtered.slice((page - 1) * PAGE_SIZE, page * PAGE_SIZE)

  if (status === 'forbidden') return <AdminForbidden />

  return (
    <div className="mx-auto max-w-5xl px-6 py-10 sm:py-14">
      <SEO title="Admin — Member Links | InviteMyPeople" path="/admin/invites" noindex />

      <p className="text-xs uppercase tracking-[0.2em] text-ink-soft">Admin Panel</p>
      <h1 className="mt-1 flex items-center gap-2 font-serif text-3xl text-ink">
        <Link2 className="h-6 w-6 text-rose" />
        Member Links
      </h1>
      <p className="mt-1 text-sm text-ink-soft">
        Every invite in the system — created directly by a couple or generated by a partner — with its
        member link and host dashboard link.
      </p>

      <div className="mt-6 flex flex-wrap items-center justify-between gap-3">
        <div className="inline-flex rounded-full border border-champagne-deep/50 bg-ivory/70 p-1">
          {SOURCE_TABS.map((tab) => (
            <button
              key={tab.value}
              type="button"
              onClick={() => setSource(tab.value)}
              className={`rounded-full px-4 py-1.5 text-sm font-medium transition-colors ${
                source === tab.value ? 'bg-rose text-ivory shadow-card' : 'text-ink-soft hover:text-ink'
              }`}
            >
              {tab.label}
            </button>
          ))}
        </div>
        <div className="relative">
          <Search className="pointer-events-none absolute left-3 top-1/2 h-3.5 w-3.5 -translate-y-1/2 text-ink-soft/60" />
          <input
            type="text"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search name, venue, partner…"
            className="w-64 rounded-full border border-champagne-deep/50 bg-ivory/70 py-2 pl-9 pr-4 text-sm text-ink placeholder:text-ink-soft/60 focus:border-rose focus:outline-none"
          />
        </div>
      </div>

      <div className="mt-6">
        {status === 'loading' && (
          <div className="flex items-center gap-2 py-16 text-ink-soft">
            <Loader2 className="h-4 w-4 animate-spin" />
            Loading invites…
          </div>
        )}
        {status === 'error' && <p className="py-16 text-ink-soft">Could not load invites.</p>}

        {status === 'success' && (
          <>
            {filtered.length === 0 ? (
              <div className="rounded-2xl border border-white/60 bg-ivory/50 px-5 py-10 text-center text-ink-soft">
                No invites match.
              </div>
            ) : (
              <div className="space-y-3">
                {pageInvites.map((inv) => (
                  <div
                    key={inv.id}
                    className="rounded-2xl border border-white/60 bg-ivory/60 px-5 py-4 shadow-soft"
                  >
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <div className="flex min-w-0 flex-wrap items-center gap-2">
                        <p className="truncate text-ink">{inv.names}</p>
                        <SourceBadge source={inv.source} businessName={inv.businessName} />
                      </div>
                      <span className="shrink-0 text-xs text-ink-soft/70">
                        {inv.eventDate ? formatInviteDate(inv.eventDate) || inv.eventDate : 'No date set'}
                      </span>
                    </div>
                    <p className="mt-0.5 truncate text-xs text-ink-soft/70">
                      {inv.venue}
                      {inv.hostEmail ? ` · ${inv.hostEmail}` : ''}
                    </p>
                    <div className="mt-3 space-y-1.5">
                      <LinkRow label="Member" url={inv.memberLink} />
                      <LinkRow label="Dashboard" url={inv.dashboardLink} />
                    </div>
                  </div>
                ))}
              </div>
            )}
            <div className="mt-2 flex items-center gap-1.5 text-xs text-ink-soft/70">
              <Gauge className="h-3 w-3" />
              {filtered.length} invite{filtered.length === 1 ? '' : 's'}
            </div>
            <Pagination page={page} pageCount={pageCount} onChange={setPage} />
          </>
        )}
      </div>
    </div>
  )
}
